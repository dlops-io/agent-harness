from formaggio.agents.runtime import MODEL_OPTIONS
from formaggio.agents.skill_support import SKILLS_ROOT, SkillFiles

PROMPTS = {1: "shop_assistant.md", 2: "shop_assistant.md", 3: "cart_proposer.md",
           4: "event_planner.md", 5: "skills_planner.md", 6: "composition_assistant.md"}


def select_cases(act, case_ids=None, context=None):
    if act not in PROMPTS:
        raise ValueError("Choose an act from 1 through 6.")
    all_cases = load_json("agent_evaluation_cases.json")
    selected = [c for c in all_cases if act in c["acts"] and (not case_ids or c["case_id"] in case_ids)]
    if case_ids and set(case_ids) - {c["case_id"] for c in selected}:
        raise ValueError("Unknown or inapplicable case(s): " + ", ".join(sorted(set(case_ids) - {c["case_id"] for c in selected})))
    if context not in {None, "basic", "enriched", "both"} or (act not in {1, 2} and context) or (act == 1 and context not in {None, "basic"}):
        raise ValueError("Context comparison applies to Act 2; Act 1 uses basic context.")
    modes = (["basic", "enriched"] if context in {None, "both"} else [context]) if act == 2 else ["basic" if act == 1 else None]
    expanded = [{**c, "context": m, "case_id": c["case_id"] + (":" + m if act == 2 else "")} for c in selected for m in modes]
    return expanded, [c["case_id"] for c in all_cases if c not in selected]


def source_state():
    return {"source_hashes": source_hashes(),
            "data": {p.name: json.loads(p.read_text()) for p in sorted((ROOT / "data").glob("*.json"))}}


class BatchRecorder:
    """Delegate recording while attaching exactly one lesson run to a batch slot."""
    def __init__(self, recorder, experiment_id, case_id, repetition):
        self.recorder, self.experiment_id = recorder, experiment_id
        self.case_id, self.repetition, self.run_id = case_id, repetition, None

    def __getattr__(self, name):
        return getattr(self.recorder, name)

    def start_run(self, version_id, **kwargs):
        if self.run_id:
            raise RuntimeError("A batch slot must contain exactly one lesson run.")
        kwargs.update(experiment_id=self.experiment_id, case_id=self.case_id, repetition=self.repetition)
        self.run_id = self.recorder.start_run(version_id, **kwargs)
        return self.run_id


async def dispatch(recorder, act, case, *, model, fixture, prompt, proposer_prompt, skills_root, output_root, progress):
    async def decision(review):
        # Explicit scenario test response, never generated by the model.
        return case["decision"]
    common = dict(model=model, scenario=case["scenario"], progress=progress, prompt=prompt)
    if act in {1, 2}:
        from act1_agent import run_agent
        if fixture:
            from formaggio.fixtures.evaluation_fixture import ProposalFixture
            async with ProposalFixture(case["expect"]).client() as client:
                return await run_agent(recorder, **common, act=act, mode=case["context"], api_client=client, execution_mode="fixture")
        return await run_agent(recorder, **common, act=act, mode=case["context"])
    if act == 3:
        from act3_workflow import run_act3
        return await run_act3(recorder, **common, fixture=fixture, manager=decision, decision_source="evaluation_fixture")
    if act == 6:
        from act6_composition import run_act6
        return await run_act6(recorder, **common, fixture=fixture, manager=decision, decision_source="evaluation_fixture",
                              skills_root=skills_root, proposer_prompt=proposer_prompt)
    from act4_harness import run_act4
    from act5_skills import run_act5
    with TemporaryDirectory(prefix="formaggio-eval-memory-") as directory:
        extra = {"skills_root": skills_root} if act == 5 else {}
        return await (run_act5 if act == 5 else run_act4)(recorder, **common, **extra, fixture=fixture,
            document=case.get("document", "clean"), reviewer=decision, decision_source="evaluation_fixture",
            memory_path=Path(directory) / "memory.sqlite", output_root=output_root)


def observations(recorder, run_id, normalized, result=None):
    events = recorder.timeline(run_id)
    requests = [e for e in events if e["event_type"] == "model.request"]
    responses = [e["payload"] for e in events if e["event_type"] == "model.response"]
    usages = [p.get("usage") or {} for p in responses]
    usage = {}
    for key in ("input_token_count", "output_token_count", "total_token_count"):
        values = [u.get(key) for u in usages]
        usage[key] = sum(values) if len(values) == len(requests) and values and all(isinstance(v, (int, float)) for v in values) else None
    run = recorder.query("SELECT started_at,ended_at FROM runs WHERE run_id=?", (run_id,))[0]
    duration = ((datetime.fromisoformat(run["ended_at"]) - datetime.fromisoformat(run["started_at"])).total_seconds()
                if run["ended_at"] else None)
    result = result or {}
    text = (result["reply"].message if "reply" in result else result["outcome"].message if "outcome" in result else result.get("agent_text"))
    text = recorder.redactor.clean(text)
    return {"normalized_output": normalized, "output_fingerprint": sha256(canonical(normalized).encode()).hexdigest(),
            "response_text": text, "response_fingerprint": sha256(text.encode()).hexdigest() if text is not None else None,
            "tool_path": [e["payload"]["name"] for e in events if e["event_type"] == "tool.requested"],
            "model_calls": len(requests), "usage": usage, "duration_seconds": duration,
            "missing_usage_calls": len(requests) - sum(bool(u) for u in usages)}


async def run_live_suite(recorder, label, *, act, repeats=5, case_ids=None, context=None, model=MODEL,
                         fixture=False, prompt=None, proposer_prompt=None, skills_root=SKILLS_ROOT,
                         output_root=OUTPUT_DIR, progress=None, runner=None):
    """runner injection is restricted to offline tests; normal execution uses dispatch."""
    if runner and not fixture:
        raise ValueError("Injected evaluation runners must be labeled fixture mode.")
    selected, excluded = select_cases(act, case_ids, context)
    if not 1 <= repeats <= 20 or len(selected) * repeats > 100:
        raise ValueError("Use 1–20 repeats and at most 100 scheduled runs per batch.")
    if recorder.query("SELECT 1 FROM experiments WHERE label=?", (label,)):
        raise ValueError("Experiment label already exists. Choose a new label; previous results are immutable.")
    prompt = (ROOT / "prompts" / PROMPTS[act]).read_text() if prompt is None else prompt
    proposer_prompt = ((ROOT / "prompts/cart_proposer.md").read_text() if proposer_prompt is None else proposer_prompt) if act == 6 else None
    initial = source_state()
    skills = SkillFiles(skills_root).files if act in {5, 6} else {}
    snapshot = {**initial, "kind": "agent_evaluation", "act": act, "mode": "fixture" if fixture else "live",
                "model": "fixture-model" if fixture else model, "options": MODEL_OPTIONS, "prompt": prompt,
                "proposer_prompt": proposer_prompt, "skills": skills, "cases": selected, "excluded_cases": excluded,
                "decision_source": "evaluation_fixture", "state_reset": "Fresh state per run; no shared preference memory.",
                "dependencies": {n: version(n) for n in ("agent-framework", "openai", "pydantic")}}
    version_id = recorder.version(snapshot)
    evaluator_version = sha256((Path(__file__).read_bytes() + Path(__file__).with_name("evaluation_checks.py").read_bytes()
                                + canonical({"act": act, "cases": selected}).encode())).hexdigest()
    experiment_id = recorder.experiment(label, version_id, evaluator_version, [c["case_id"] for c in selected], repeats)
    failures = 0
    if progress:
        progress(f"{'FIXTURE' if fixture else 'LIVE'} evaluation: {len(selected)} cases × {repeats} repeats = {len(selected) * repeats} runs.")
        progress("Approval responses are explicit scenario TEST decisions. Operational state resets each run.")
        progress("Excluded cases: " + ", ".join(excluded))
    for case in selected:
        for repetition in range(1, repeats + 1):
            bound = BatchRecorder(recorder, experiment_id, case["case_id"], repetition)
            changed = False
            result = None
            normalized = {"status": "error"}
            if progress:
                progress(f"Case {case['case_id']} — repeat {repetition}/{repeats}")
            try:
                changed = source_state() != initial or (bool(skills) and SkillFiles(skills_root).files != skills)
                if changed:
                    raise RuntimeError("Source/data/skills changed during this batch. Start a new labeled batch.")
                result = await (runner or dispatch)(bound, act, case, model="fixture-model" if fixture else model,
                    fixture=fixture, prompt=prompt, proposer_prompt=proposer_prompt, skills_root=skills_root,
                    output_root=Path(output_root) / "evaluations" / experiment_id, progress=progress)
                if not bound.run_id or result["run_id"] != bound.run_id:
                    raise RuntimeError("Runner did not return its recorded batch run.")
                changed = source_state() != initial or (bool(skills) and SkillFiles(skills_root).files != skills)
                if changed:
                    raise RuntimeError("Source/data/skills changed during execution; result is not comparable.")
                checks, normalized = assess_run(act, case, result, recorder.timeline(bound.run_id))
                for check in checks:
                    recorder.evaluation(bound.run_id, check, evaluator_version)
                failures = 0
            except asyncio.CancelledError:
                raise
            except Exception as exc:
                if bound.run_id is None:
                    bound.start_run(version_id, act=act, model=snapshot["model"], mode=snapshot["mode"])
                recorder.evaluation(bound.run_id, CheckResult(check_id="execution", expected="completed",
                    observed=type(exc).__name__, status="error", explanation=str(exc)), evaluator_version)
                recorder.finish_run(bound.run_id, "error", str(exc))
                failures += 1
            recorder.event(bound.run_id, "evaluation.observation", observations(recorder, bound.run_id, normalized, result))
            if changed or failures >= 3:
                recorder.event(bound.run_id, "evaluation.batch_stopped", {"reason": "Configuration changed." if changed else "Three consecutive execution errors."})
                return report_experiment(recorder, label)
    return report_experiment(recorder, label)
